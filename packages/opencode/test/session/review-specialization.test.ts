const useServerConfig = Effect.gen(function* () {
  const { directory: dir } = yield* TestInstance
  const llm = yield* TestLLMServer
  const fs = yield* FSUtil.Service
  yield* fs.writeWithDirs(
    path.join(dir, "opencode.json"),
    JSON.stringify({
      $schema: "https://opencode.ai/config.json",
      ...cfg,
      provider: {
        ...cfg.provider,
        test: { ...cfg.provider.test, options: { ...cfg.provider.test.options, baseURL: llm.url } },
      },
    }),
  )
  return { dir, llm }
})

it.instance(
  "Work and Code review agents have distinct prompts in the agent registry",
  () =>
    Effect.gen(function* () {
      const agent = yield* AgentSvc.Service
      const workReview = yield* agent.get("work-review")
      const codeReview = yield* agent.get("code-review")
      const genericReview = yield* agent.get("review")

      expect(workReview).toBeDefined()
      expect(codeReview).toBeDefined()
      expect(genericReview).toBeDefined()

      expect(workReview?.name).toBe("work-review")
      expect(codeReview?.name).toBe("code-review")
      expect(genericReview?.name).toBe("review")

      // Work review prompt should mention workspace tasks
      expect(workReview?.prompt).toContain("general workspace tasks")
      expect(workReview?.prompt).toContain("Senior Work Reviewer")

      // Code review prompt should mention code-specific concerns
      expect(codeReview?.prompt).toContain("spec compliance, correctness, tests, types, integration, regressions")
      expect(codeReview?.prompt).toContain("Senior Code Reviewer")

      // Generic review should still exist
      expect(genericReview?.prompt).toContain("Senior Code Reviewer")
    }),
  10_000,
)